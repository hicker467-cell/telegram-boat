def make_clean_q(question, options, correct_idx, explanation=""):
    q = question.strip()
    opts = [o.strip() for o in options]
    assert len(opts) == 4, f"Options must be 4: {opts}"
    assert 0 <= correct_idx <= 3, f"Invalid correct_idx: {correct_idx}"
    assert "$" not in q, f"$ found: {q}"
    for o in opts:
        assert "$" not in o, f"$ in option: {o}"
    if not explanation:
        explanation = f"सही उत्तर विकल्प ({chr(65 + correct_idx)}) है।"
    return {
        "question": q,
        "options": opts,
        "correct_option_id": correct_idx,
        "explanation": explanation
    }

